# Лямбда-функція: це дуже коротка функція в один рядок.
# Вона бере число (p) і робить з нього текст з двома нулями після коми і припискою "грн"
format_price = lambda p: f"{float(p):.2f}грн"


# Функція, яка показує всі товари
def show(cat):
    print("\n--- КАТАЛОГ ---")
    # Метод .items() дістає зі словника одразу пару: ключ (k - це ID товару) і значення (v - вся інформація про нього)[cite: 1]
    for k, v in cat.items():
        # v['n'].title() бере назву і робить першу букву великою (ноутбук -> Ноутбук)[cite: 2]
        print(f"ID:{k} | {v['n'].title()} | {format_price(v['p'])} | Залишок: {v['s']} шт.")


# Функція для додавання товару в кошик
def add(cart, cat):
    show(cat)  # Спочатку показуємо каталог, щоб знати, що вибирати
    # input() чекає, поки ти щось введеш. .strip() обрізає випадкові пробіли, якщо ти випадково їх натиснув[cite: 2]
    p_id = input("Введіть ID для додавання: ").strip()

    # cat.get(p_id) перевіряє, чи взагалі існує такий ID. А cat[p_id]['s'] > 0 перевіряє, чи є товар на складі[cite: 1]
    if cat.get(p_id) and cat[p_id]['s'] > 0:
        cart.append(p_id)  # Метод .append() закидає цей ID в кінець списку нашого кошика[cite: 1]
        cat[p_id]['s'] -= 1  # Віднімаємо 1 штуку зі складу (бо ми її забрали)
        print("✅ Додано!")
    else:
        print("❌ Помилка: немає в наявності або невірний ID.")


# Функція для перегляду того, що ми вже навибирали
def view(cart, cat):
    # Якщо список cart порожній (нічого не додавали), пишемо про це і відразу зупиняємо функцію
    if not cart: return print("Кошик порожній.") or False

    print("\n--- КОШИК ---")
    # set(cart) залишає тільки унікальні ID[cite: 2]. Щоб якщо ти додав 3 мишки, ми не писали "мишка, мишка, мишка", а згрупували їх.
    for i in set(cart):
        # cart.count(i) рахує, скільки саме разів цей ID зустрічається в кошику[cite: 1]
        print(f"{cat[i]['n']} - {cart.count(i)} шт.")

        # Рахуємо гроші: беремо ціну кожного товару, який лежить у кошику, і додаємо до купи
    print(f"Сума: {format_price(sum(cat[i]['p'] for i in cart))}")
    return True  # Кажемо програмі: "Все ок, кошик не порожній"


# Функція для викидання товару з кошика
def remove(cart, cat):
    # Якщо кошик не порожній (view повернув True), дозволяємо видаляти
    if view(cart, cat):
        p_id = input("ID для видалення: ").strip()
        if p_id in cart:
            cart.remove(p_id)  # Метод .remove() знаходить цей ID у списку і викидає його[cite: 1]
            cat[p_id]['s'] += 1  # Повертаємо 1 штуку назад на склад магазину
            print("✅ Видалено!")


# Функція покупки
def buy(cart, cat):
    # Показуємо кошик і питаємо згоду. .lower() робить всі букви маленькими, щоб програма зрозуміла і "ТАК", і "так", і "Так"[cite: 2]
    if view(cart, cat) and input("Оплатити? (так/ні): ").strip().lower() == 'так':
        cart.clear()  # Повністю очищаємо список кошика
        print("🎉 Оплачено!")


# Секретна функція для адміна
def admin(cat):
    if input("Пароль: ").strip() == "admin":
        for k, v in cat.items():  # Знову перебираємо весь каталог[cite: 1]
            print(f"[{k}] {v['n']}: {v['s']} шт.")
    else:
        print("❌ Відмовлено.")


# Головна функція, де все запускається
def main():
    # Наш каталог. Це словник у словнику.
    # Ключі "1", "2", "3" - це ID. А всередині: n - назва, p - ціна, s - залишок на складі.
    cat = {
        "1": {"n": "ноутбук", "p": 25000, "s": 5},
        "2": {"n": "мишка", "p": 850, "s": 15},
        "3": {"n": "клавіатура", "p": 2100, "s": 8}
    }
    cart = []  # Це наш кошик. Зараз це просто порожній список.

    # Безкінечний цикл `while True`. Меню буде з'являтися постійно, поки ми самі не натиснемо "0" для виходу.
    while True:
        cmd = input("\n1.Каталог 2.Додати 3.Кошик 4.Видалити 5.Купити 6.Адмін 0.Вихід\nВибір: ").strip()
        if cmd == "0":
            break  # Команда break ламає цикл, програма закривається
        elif cmd == "1":
            show(cat)  # Залежно від цифри, запускається відповідна функція, які ми розписали вище
        elif cmd == "2":
            add(cart, cat)
        elif cmd == "3":
            view(cart, cat)
        elif cmd == "4":
            remove(cart, cat)
        elif cmd == "5":
            buy(cart, cat)
        elif cmd == "6":
            admin(cat)


# Обов'язкова точка входу.
# Вона буквально каже системі: "Якщо цей файл запустили напряму, то виконай функцію main()"
if __name__ == "__main__":
    main()